[CmdletBinding()]
param(
    [ValidateSet("start", "stop", "restart", "status", "logs", "install")]
    [string]$Action = "start",
    [ValidateSet("auto", "local", "docker")]
    [string]$Mode = "auto",
    # The July 19 tree is the standalone CTF instance. Keep its control plane
    # separate from the current pentest Cairn, which uses port 8000.
    [int]$Port = 8001,
    [string]$Config = "",
    [string]$DbPath = "",
    [switch]$NoBrowser,
    [switch]$ForceInstall
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$RuntimeDir = Join-Path $Root ".cairn-launcher"
$StatePath = Join-Path $RuntimeDir "state.json"
$VenvDir = Join-Path $Root ".venv"
$VenvPython = Join-Path $VenvDir "Scripts\python.exe"
$CairnExe = Join-Path $VenvDir "Scripts\cairn.exe"

function Write-Step([string]$Message) { Write-Host "[Cairn CTF] $Message" -ForegroundColor Cyan }
function Write-Ok([string]$Message) { Write-Host "[Cairn CTF OK] $Message" -ForegroundColor Green }

function Ensure-Directory([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path)) {
        New-Item -ItemType Directory -Path $Path -Force | Out-Null
    }
}

function Test-Command([string]$Name) {
    return $null -ne (Get-Command $Name -ErrorAction SilentlyContinue)
}

function Ensure-Venv {
    Ensure-Directory $RuntimeDir
    if (-not (Test-Path -LiteralPath $VenvPython)) {
        Write-Step "Creating Python 3.12 virtual environment..."
        if (Test-Command "py") {
            & py -3.12 -m venv $VenvDir
        }
        elseif (Test-Command "python") {
            $version = & python -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')"
            if ([version]$version -lt [version]"3.12") { throw "Python 3.12+ is required; found $version." }
            & python -m venv $VenvDir
        }
        else {
            throw "Python 3.12+ was not found. Install Python, then run this launcher again."
        }
        if ($LASTEXITCODE -ne 0) { throw "Failed to create the virtual environment." }
    }

    $needsInstall = $ForceInstall -or -not (Test-Path -LiteralPath $CairnExe)
    if (-not $needsInstall) {
        & $VenvPython -c "import cairn, fastapi, uvicorn, yaml, requests" 2>$null
        $needsInstall = $LASTEXITCODE -ne 0
    }
    if ($needsInstall) {
        Write-Step "Installing Cairn and its Python dependencies..."
        & $VenvPython -m pip install -e (Join-Path $Root "cairn")
        if ($LASTEXITCODE -ne 0) {
            throw "Dependency installation failed. Check the network/proxy and retry with: .\cairn-launcher.ps1 install"
        }
    }
    Write-Ok "Python environment is ready."
}

function Quote-Yaml([string]$Value) { return "'" + $Value.Replace("'", "''") + "'" }

function New-LocalConfig([int]$ListenPort) {
    $configPath = Join-Path $RuntimeDir "dispatch.local.generated.yaml"
    $workspace = Join-Path $RuntimeDir "runs"
    Ensure-Directory $workspace
    $serverUrl = "http://127.0.0.1:$ListenPort"
    $content = @"
# Generated by cairn-launcher.ps1. Use -Config to supply your own dispatcher config.
server: $(Quote-Yaml $serverUrl)

runtime:
  execution: api
  server_managed_agents: true
  worker_healthcheck: startup_and_task
  max_workers: 2
  max_running_projects: 2
  max_project_workers: 2
  interval: 3
  healthcheck_timeout: 60
  prompt_group: default

tasks:
  bootstrap:
    timeout: 300
    conclude_timeout: 60
  reason:
    timeout: 240
  explore:
    timeout: 600
    conclude_timeout: 120

local:
  workspace_root: $(Quote-Yaml $workspace)
  completed_action: keep

workers: []
"@
    Set-Content -LiteralPath $configPath -Value $content -Encoding UTF8
    Write-Ok "Generated server-managed Agent API config: $configPath"
    return $configPath
}

function Resolve-Config([int]$ListenPort) {
    if ($Config) {
        $candidate = $Config
        if (-not [System.IO.Path]::IsPathRooted($candidate)) { $candidate = Join-Path $Root $candidate }
        if (-not (Test-Path -LiteralPath $candidate -PathType Leaf)) { throw "Dispatcher config not found: $candidate" }
        return (Resolve-Path -LiteralPath $candidate).Path
    }
    return New-LocalConfig $ListenPort
}

function Test-Http([string]$Url) {
    try {
        $response = Invoke-WebRequest -Uri "$Url/projects" -UseBasicParsing -TimeoutSec 2
        return $response.StatusCode -ge 200 -and $response.StatusCode -lt 300
    }
    catch { return $false }
}

function Wait-ForServer([string]$Url, [int]$Seconds = 30) {
    $deadline = (Get-Date).AddSeconds($Seconds)
    while ((Get-Date) -lt $deadline) {
        if (Test-Http $Url) { return $true }
        Start-Sleep -Milliseconds 500
    }
    return $false
}

function Read-State {
    if (-not (Test-Path -LiteralPath $StatePath -PathType Leaf)) { return $null }
    try { return Get-Content -Raw -LiteralPath $StatePath | ConvertFrom-Json }
    catch { return $null }
}

function Test-ProcessId([object]$ProcessId) {
    if ($null -eq $ProcessId) { return $false }
    return $null -ne (Get-Process -Id ([int]$ProcessId) -ErrorAction SilentlyContinue)
}

function Stop-ProcessTree([object]$ProcessId, [object]$ExpectedStartedAt = $null) {
    if (-not (Test-ProcessId $ProcessId)) { return }
    $process = Get-Process -Id ([int]$ProcessId) -ErrorAction SilentlyContinue
    if ($null -ne $process -and $null -ne $ExpectedStartedAt) {
        $expected = [datetime]$ExpectedStartedAt
        if ([math]::Abs(($process.StartTime - $expected).TotalMinutes) -gt 2) {
            Write-Warning "PID $ProcessId appears to have been reused; it was not stopped."
            return
        }
    }
    # taskkill normally removes the complete dispatcher/worker tree. Some managed
    # Windows environments deny it, so suppress its diagnostics and fall back to
    # terminating the wrapper process directly.
    & $env:ComSpec /D /C "taskkill /PID $ProcessId /T /F >NUL 2>NUL" | Out-Null
    if (Test-ProcessId $ProcessId) {
        Stop-Process -Id ([int]$ProcessId) -Force -ErrorAction SilentlyContinue
    }
}

function Quote-CmdToken([string]$Value) {
    if ($Value.Contains('"')) { throw "A launcher path or argument contains an unsupported double quote: $Value" }
    return '"' + $Value + '"'
}

function Start-BackgroundCommand(
    [string]$Executable,
    [string[]]$Arguments,
    [string]$WorkingDirectory,
    [string]$StandardOutput,
    [string]$StandardError
) {
    # A tiny Python wrapper owns the redirected file handles and reports the actual
    # Cairn PID. This avoids Start-Process environment bugs and lets stop/status target
    # the service rather than an intermediate cmd.exe process.
    $specPath = $StandardOutput + ".runner.json"
    $pidPath = $StandardOutput + ".pid"
    Remove-Item -LiteralPath $pidPath -Force -ErrorAction SilentlyContinue
    [ordered]@{
        executable = $Executable
        arguments = @($Arguments)
        cwd = $WorkingDirectory
        stdout = $StandardOutput
        stderr = $StandardError
        pid_file = $pidPath
    } | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath $specPath -Encoding UTF8

    $startInfo = New-Object System.Diagnostics.ProcessStartInfo
    $startInfo.FileName = $VenvPython
    $startInfo.Arguments = (Quote-CmdToken (Join-Path $Root "cairn-launcher-runner.py")) + ' ' + (Quote-CmdToken $specPath)
    $startInfo.WorkingDirectory = $WorkingDirectory
    $startInfo.UseShellExecute = $false
    $startInfo.CreateNoWindow = $true
    $process = New-Object System.Diagnostics.Process
    $process.StartInfo = $startInfo
    if (-not $process.Start()) { throw "Failed to start $Executable" }
    $deadline = (Get-Date).AddSeconds(10)
    while ((Get-Date) -lt $deadline -and -not (Test-Path -LiteralPath $pidPath)) {
        if ($process.HasExited) { throw "Background runner exited before starting $Executable" }
        Start-Sleep -Milliseconds 100
    }
    if (-not (Test-Path -LiteralPath $pidPath)) { throw "Timed out waiting for $Executable to report its PID" }
    return [pscustomobject]@{
        Id = [int](Get-Content -Raw -LiteralPath $pidPath)
        RunnerId = $process.Id
    }
}

function Open-CairnUrl([string]$Url) {
    $startInfo = New-Object System.Diagnostics.ProcessStartInfo
    $startInfo.FileName = $Url
    $startInfo.UseShellExecute = $true
    [System.Diagnostics.Process]::Start($startInfo) | Out-Null
}

function Assert-LocalNetwork {
    Ensure-Venv
    $database = $DbPath
    if (-not $database) { $database = Join-Path $RuntimeDir "data\cairn.db" }
    if (-not [System.IO.Path]::IsPathRooted($database)) { $database = Join-Path $Root $database }
    & $VenvPython (Join-Path $Root "cairn-launcher-network.py") $database
    if ($LASTEXITCODE -ne 0) { throw "Local network preflight failed. No services were stopped or started." }
}

function Start-Local {
    Ensure-Venv
    $existing = Read-State
    if ($null -ne $existing -and (Test-ProcessId $existing.server_pid) -and (Test-Http $existing.url)) {
        Write-Ok "Cairn CTF is already running at $($existing.url)"
        return
    }

    $url = "http://127.0.0.1:$Port"
    if (Test-Http $url) { throw "Port $Port already hosts a Cairn-compatible service that this launcher does not manage." }

    $configPath = Resolve-Config $Port
    $database = $DbPath
    if (-not $database) { $database = Join-Path $RuntimeDir "data\cairn.db" }
    if (-not [System.IO.Path]::IsPathRooted($database)) { $database = Join-Path $Root $database }
    Ensure-Directory (Split-Path -Parent $database)

    $stamp = Get-Date -Format "yyyyMMdd-HHmmss-fffffff"
    $logDir = Join-Path $RuntimeDir "logs\$stamp"
    Ensure-Directory $logDir
    $serverOut = Join-Path $logDir "server.stdout.log"
    $serverErr = Join-Path $logDir "server.stderr.log"
    $dispatcherOut = Join-Path $logDir "dispatcher.stdout.log"
    $dispatcherErr = Join-Path $logDir "dispatcher.stderr.log"

    $server = $null
    $dispatcher = $null
    try {
        Write-Step "Starting Cairn CTF server on $url ..."
        $server = Start-BackgroundCommand -Executable $CairnExe -Arguments @(
            "serve", "--host", "127.0.0.1", "--port", [string]$Port,
            "--db-path", $database, "--no-access-log"
        ) -WorkingDirectory $Root -StandardOutput $serverOut -StandardError $serverErr

        if (-not (Wait-ForServer $url 30)) { throw "Server did not become healthy. See $serverErr" }

        Write-Step "Starting Cairn CTF dispatcher..."
        $dispatcher = Start-BackgroundCommand -Executable $CairnExe -Arguments @(
            "dispatch", "--config", $configPath
        ) -WorkingDirectory $Root -StandardOutput $dispatcherOut -StandardError $dispatcherErr
        Start-Sleep -Seconds 2
        if (-not (Test-ProcessId $dispatcher.Id)) { throw "Dispatcher exited during startup. See $dispatcherErr" }

        [ordered]@{
            mode = "local"
            url = $url
            port = $Port
            server_pid = $server.Id
            dispatcher_pid = $dispatcher.Id
            server_runner_pid = $server.RunnerId
            dispatcher_runner_pid = $dispatcher.RunnerId
            config = $configPath
            database = $database
            log_dir = $logDir
            started_at = (Get-Date).ToString("o")
        } | ConvertTo-Json | Set-Content -LiteralPath $StatePath -Encoding UTF8

        Write-Ok "Cairn CTF started: $url"
        Write-Host "Logs: $logDir"
        if (-not $NoBrowser) { Open-CairnUrl $url }
    }
    catch {
        if ($null -ne $dispatcher) { Stop-ProcessTree $dispatcher.Id }
        if ($null -ne $server) { Stop-ProcessTree $server.Id }
        if ($null -ne $dispatcher) { Stop-Process -Id $dispatcher.RunnerId -Force -ErrorAction SilentlyContinue }
        if ($null -ne $server) { Stop-Process -Id $server.RunnerId -Force -ErrorAction SilentlyContinue }
        throw
    }
}

function Stop-Local {
    $state = Read-State
    if ($null -eq $state) { Write-Host "Cairn CTF launcher has no saved local process state."; return }
    Stop-ProcessTree $state.dispatcher_pid $state.started_at
    Stop-ProcessTree $state.server_pid $state.started_at
    if ($state.PSObject.Properties.Name -contains "dispatcher_runner_pid") {
        Stop-Process -Id ([int]$state.dispatcher_runner_pid) -Force -ErrorAction SilentlyContinue
    }
    if ($state.PSObject.Properties.Name -contains "server_runner_pid") {
        Stop-Process -Id ([int]$state.server_runner_pid) -Force -ErrorAction SilentlyContinue
    }
    Remove-Item -LiteralPath $StatePath -Force -ErrorAction SilentlyContinue
    Write-Ok "Cairn CTF stopped."
}

function Show-LocalStatus {
    $state = Read-State
    Write-Host "Instance:   Cairn CTF"
    if ($null -eq $state) { Write-Host "Status:     stopped"; return }
    $serverRunning = Test-ProcessId $state.server_pid
    $dispatcherRunning = Test-ProcessId $state.dispatcher_pid
    $healthy = Test-Http $state.url
    Write-Host "URL:        $($state.url)"
    Write-Host "Server:     $(if ($serverRunning) { 'running' } else { 'stopped' }) (PID $($state.server_pid))"
    Write-Host "Dispatcher: $(if ($dispatcherRunning) { 'running' } else { 'stopped' }) (PID $($state.dispatcher_pid))"
    Write-Host "Health:     $(if ($healthy) { 'healthy' } else { 'unreachable' })"
    Write-Host "Logs:       $($state.log_dir)"
}

function Show-LocalLogs {
    $state = Read-State
    if ($null -eq $state -or -not (Test-Path -LiteralPath $state.log_dir)) { Write-Host "No launcher logs found."; return }
    foreach ($name in @("server.stdout.log", "server.stderr.log", "dispatcher.stdout.log", "dispatcher.stderr.log")) {
        $path = Join-Path $state.log_dir $name
        if (Test-Path -LiteralPath $path) {
            Write-Host "`n===== $name =====" -ForegroundColor Yellow
            Get-Content -LiteralPath $path -Tail 60
        }
    }
}

function Resolve-Mode {
    if ($Mode -ne "auto") { return $Mode }
    return "local"
}

function Invoke-Docker([string]$DockerAction) {
    if (-not (Test-Command "docker")) { throw "Docker was not found on PATH." }
    if (-not (Test-Path -LiteralPath (Join-Path $Root "dispatch.yaml"))) {
        throw "Docker mode requires dispatch.yaml. Copy dispatch.example.yaml and fill in the worker API settings first."
    }
    # Use a distinct Compose project and host port so this tree can run next to
    # the current Cairn Docker stack without sharing containers or listeners.
    $env:CAIRN_HOST_PORT = [string]$Port
    $env:COMPOSE_PROJECT_NAME = "cairn-ctf"
    Push-Location $Root
    try {
        switch ($DockerAction) {
            "start"   { & docker compose up --build -d }
            "stop"    { & docker compose down }
            "status"  { & docker compose ps }
            "logs"    { & docker compose logs --tail 100 }
            "restart" { & docker compose down; if ($LASTEXITCODE -eq 0) { & docker compose up --build -d } }
        }
        if ($LASTEXITCODE -ne 0) { throw "docker compose $DockerAction failed." }
        if ($DockerAction -in @("start", "restart")) {
            Write-Ok "Cairn CTF Docker services started: http://127.0.0.1:$Port"
            if (-not $NoBrowser) { Open-CairnUrl "http://127.0.0.1:$Port" }
        }
    }
    finally { Pop-Location }
}

try {
    Set-Location $Root
    if ($Action -eq "install") { Ensure-Venv; exit 0 }
    $selectedMode = Resolve-Mode
    if ($selectedMode -eq "docker") { Invoke-Docker $Action; exit 0 }
    switch ($Action) {
        "start"   { Assert-LocalNetwork; Start-Local }
        "stop"    { Stop-Local }
        "restart" { Assert-LocalNetwork; Stop-Local; Start-Local }
        "status"  { Show-LocalStatus }
        "logs"    { Show-LocalLogs }
    }
}
catch {
    Write-Host "[ERROR] $($_.Exception.Message)" -ForegroundColor Red
    exit 1
}
